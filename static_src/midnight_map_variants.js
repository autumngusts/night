// 自動辨識文字——跟原版SPIRIT_BIRD_LINKS的既有做法（第一輪肉眼描、之後視情況修正）同一等級
// 的精確度，尤其F的來源/目的地配對（哪條白色曲線連到哪個目的地）是依曲線視覺方向人工判斷，
// 不是逐像素還原原畫路徑。如果之後實測發現座標或F配對跟原意有落差，應該重新核對對應
// annotated圖再修正這份資料，不需要整個重寫（同midnight_map.js既有的SPIRIT_BIRD_LINKS
// 註解精神）。
//
