//   cassel：中心靠左下的Z點（z_center）
//   ice：左上橘線範圍內的Z點（z_hazard，Q點也在這個範圍內）
//   kasan：上方橘線範圍內的Z點（z_lava）
//   red：右下橘線範圍內的Z點（z_hazard）
