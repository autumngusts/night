// 1個橘色區塊，代表這張地圖沒有畫王城，CASTLE_ROWS全0）——不是肉眼描格子，也不是每格手動
// 核對，是程式對標註圖做影像處理後在原圖解析度下用「每格超過一半取樣點落在範圍內」downsample
// 成48格，因此精準對齊使用者實際畫的線（跟原版FIXED_GRID_ROWS同一套方法論）。
//
// A（起點）／Z（縮圈終點）／F（靈鳥）／Q（特殊板塊，見docs的Q板塊規則）座標則是肉眼讀取
