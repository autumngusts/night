  // 但midnight_map.jsのisWalkable()／buildFixedGrid()既有慣例是相反的「0＝可走、1＝牆」
  // （沿用origin地圖FIXED_GRID_ROWS的既有寫法，不能改那邊，那是既有正式資料）。這裡解碼
  // 時把GRID_ROWS整個反相，讓對外回傳的grid欄位維持跟origin一致的「0＝可走」語意——
  // pointEligible／hazardZone／castleZone這三份資料的「1＝範圍內」語意本來就跟既有的
