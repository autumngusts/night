// (248,120,32)兩種顏色分別跑一次，橘色部分該圖若偵測到兩個獨立區塊，較大的視為「特殊事件
// 範圍」（HAZARD_ROWS，卡牌4/5/Q/可怖強敵/祝福×2的專屬區域，見docs），較小的視為「王城
