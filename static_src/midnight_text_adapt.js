  var OVERRIDE_BY_NAME = {};
  BODY_OVERRIDES.forEach(function (entry) {
    entry.names.forEach(function (n) {
      OVERRIDE_BY_NAME[n] = entry;
    });
  });

  function applyRules(text, rules) {
    var out = text;
    rules.forEach(function (rule) {
      out = out.replace(rule[0], rule[1]);
    });
    return out;
  }

  // 刪除之後可能留下的版面碎屑：連續的全形空格分隔符、行首/行尾多出來的分隔符、
  // 以及「，。」「、。」這種刪掉子句後黏起來的標點。純排版整理，不改任何語意。
  function tidy(text) {
    return text
      .replace(/　{2,}/g, "　")
      .replace(/[ \t　]+$/gm, "")
      .replace(/^[ \t　]+/gm, "")
      .replace(/[，、]。/g, "。")
      .replace(/。{2,}/g, "。")
      .replace(/\n{3,}/g, "\n\n")
      .trim();
  }

  function applyTermRules(text) {
    // 刪除規則先跑：「編隊：前衛時可使用」要在術語轉換把「前衛時可使用」換成「隨時可使用」
    // 之前就整欄吃掉，否則欄位會變成刪不掉的「編隊：隨時可使用」。
    return tidy(applyRules(applyRules(text, REMOVE_RULES[ruleLang()]), TERM_RULES[ruleLang()]));
  }

  function appendLegends(original, converted) {
    var key = ruleLang();
    var lines = [];
    LEGEND_RULES.forEach(function (rule) {
      // 預設同時比對原文與轉換後的文字（避免轉換表把關鍵字換掉之後就偵測不到）；
      // testOn:"converted" 的規則只看轉換後的文字（見該規則自己的說明）。
      var hit = rule.testOn === "converted" ? rule.test.test(converted) : rule.test.test(original) || rule.test.test(converted);
      if (hit) lines.push(rule[key]);
    });
    if (!lines.length) return converted;
    return converted + "\n" + lines.join("\n");
  }

  // adapt(body, name)
  //   body：已經 localizedText() 過的規則本文字串（非字串一律原樣回傳，方便呼叫端不必先判斷）。
  //   name：可選，該效果的顯示名稱（同樣是已 localizedText() 過的字串）。有給且命中
  //         BODY_OVERRIDES 時，整段本文改用覆寫文字，不再套用術語轉換。
  function adapt(body, name) {
    if (typeof body !== "string" || !body) return body;
    if (name && OVERRIDE_BY_NAME[name]) return OVERRIDE_BY_NAME[name][ruleLang()];
    var converted = applyTermRules(body);
    // 保險：本文整段只由「本規則不適用的敘述」構成時，刪除規則會把它清成空字串，畫面上
    // 就變成一片空白（比留著原文更糟）。這種條目應該改走 BODY_OVERRIDES 用一行說明取代；
    // 萬一漏掉，這裡退回原文，至少不會顯示空白。
    if (!converted) return body;
    return appendLegends(body, converted);
  }

  window.PriTestMidnightTextAdapt = {
    adapt: adapt,
  };
