  // ---- 雜湊（不碰 st.seed） ----
  function hash(s) {
    var h = 2166136261;
    for (var i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
    return h >>> 0;
  }
  function pickBy(list, key) { return list[hash(key) % list.length]; }
  function L(obj, lang) { return obj ? obj[lang === "zh" ? "zh" : "ja"] || obj.zh || "" : ""; }
  function idKey(a) { return String(a.rosterId || "") + ":" + a.id + ":" + a.nameSeed; }

  // 固定的個人情報（同一個人永遠一樣）
  function profile(a) {
    var k = idKey(a), h = hash(k + "#body");
    var blood = ["A", "A", "A", "A", "O", "O", "O", "B", "B", "AB"][hash(k + "#blood") % 10];
    var height = a.gender === "m" ? 165 + h % 24 : 150 + h % 23;
    var i1 = hash(k + "#t1") % TRIVIA.length, i2 = hash(k + "#t2") % (TRIVIA.length - 1);
    if (i2 >= i1) i2++;
    return {
      month: hash(k + "#bm") % 12 + 1, day: hash(k + "#bd") % 30 + 1, blood: blood, height: height,
      hobby: pickBy(HOBBIES, k + "#hobby"), food: pickBy(FOODS, k + "#food"), weak: pickBy(WEAK, k + "#weak"),
      catchphrase: pickBy(CATCH, k + "#catch"), skill: pickBy(SKILLS, k + "#skill"), trivia: [TRIVIA[i1], TRIVIA[i2]]
    };
  }

  // 生日（遊戲曆）：回傳該年的 day 序號，讓月曆標 🎂
  function birthdayOf(a, year) {
    var p = profile(a);
    return (year - 1) * D.BAL.daysPerYear + (p.month - 1) * D.BAL.daysPerMonth + (p.day - 1);
  }

  // 目前狀況下可能說的話（由具體到一般；具體的放比較多次，比較常被選到）
  function candidates(st, a) {
    var out = [], t = a.task;
    function add(arr, w) { for (var i = 0; i < (w || 1); i++) out = out.concat(arr); }
    if (t) {
      if (t.kind === "rest") add(t.forced ? (a.stress >= 60 ? M.strike : M.rest_forced) : M.rest, 3);
      else if (t.kind === "course") {
        var c = D.COURSE_BY_ID[t.courseId];
        add(M.course, 2);
        if (c && M["course_" + c.stat]) add(M["course_" + c.stat], 2);
      } else if (M[t.kind]) add(M[t.kind], 3);
    } else add(M.idle, 2);
    if (a.stamina < 30) add(M.tired, 3);
    if (a.stress > 70) add(M.stressed, 3);
    if (a.mood >= 1) add(M.happy);
    if (a.mood <= -1) add(M.sad, 2);
    if (a.contractEnd !== null && a.contractEnd - st.day <= 60 && a.contractEnd >= st.day) add(M.contract, 2);
    if (st.day - (a.joinedDay || 0) <= 14) add(M.newbie, 3);
    if (a.trophies && a.trophies.length) add(M.trophy);
    if (a.fame >= 800) add(M.famous);
    if (a.rarity === "SSR") add(M.ssr);
    if (DIR_M[a.dir]) add(DIR_M[a.dir], 2);
    return out;
  }

  function fill(text, st, a, lang) {
    var p = profile(a);
    var Core = root.PriTestStarvCore;
    var job = "";
    if (a.task && a.task.kind === "job") {
      var aj = (st.activeJobs || []).filter(function (x) { return x.id === a.task.ref; })[0];
      job = aj ? Core.jobTitle(aj.job, lang) : "";
    }
    var stat = "";
    if (a.task && a.task.kind === "course") {
      var c = D.COURSE_BY_ID[a.task.courseId];
      stat = c ? L(D.STAT_NAMES[c.stat], lang) : "";
    }
    return text.replace(/\{hobby\}/g, L(p.hobby, lang)).replace(/\{food\}/g, L(p.food, lang)).replace(/\{weak\}/g, L(p.weak, lang))
      .replace(/\{catch\}/g, L(p.catchphrase, lang)).replace(/\{job\}/g, job).replace(/\{stat\}/g, stat)
      .replace(/\{company\}/g, st.company.name || (root.I18N ? root.I18N.t("sv_company_default") : ""));
  }

  // salt 相同就說同一句（藝人詳情用「天數」當 salt，一天換一句；設施圖的對話框用隨機 salt）
  function say(st, a, lang, salt) {
    var c = candidates(st, a);
    if (!c.length) return "";
    return fill(L(c[hash(idKey(a) + "@" + salt) % c.length], lang), st, a, lang);
  }

